// ตัวจำแนกระดับความเร่งด่วนจากข้อความลูกค้า (ชุดคำเดียวกับฝั่งหน้าเว็บ)
// แดง: ตำหนิ/ด่า/ปัญหาสินค้า/ด่วน · เหลือง: ทวงถาม/รอ/ติดปัญหา · เขียว: ทั่วไป
export type UrgencyLevel = 'red' | 'yellow' | 'green';

// prettier-ignore
export const RED: readonly string[] = [
  'ห่วย', 'แย่', 'กาก', 'เฮงซวย', 'โกง', 'หลอกลวง', 'หลอก', 'ร้องเรียน', 'ฟ้อง', 'สคบ',
  'คืนเงิน', 'ขอเงินคืน', 'เคลม', 'ชำรุด', 'พัง', 'แตก', 'รั่ว', 'เสียหาย', 'ของเสีย',
  'หมดอายุ', 'ขึ้นรา', 'บูด', 'เน่า', 'สกปรก', 'มีกลิ่น', 'เหม็น', 'แพ้', 'ผื่น', 'อันตราย',
  'ผิดหวัง', 'ไม่พอใจ', 'ไม่ประทับใจ', 'บริการแย่', 'ไม่รับผิดชอบ', 'โมโห', 'โกรธ', 'แม่ง',
  'เหี้ย', 'สัส', 'ควย', 'อีดอก', 'ไอ้', 'ปลอม', 'ส่งผิด', 'ไม่ครบ', 'ไม่ตรงปก', 'ไม่แน่น',
  'รีว่ผิด', 'รีวิวผิด', 'ผิดพลาด', 'ด่วน', 'เร่งด่วน', 'ด่วนที่สุด',
];

// prettier-ignore
export const YELLOW: readonly string[] = [
  'ยังไม่ได้', 'ยังไม่ได้รับ', 'ยังไม่มา', 'ยังไม่ถึง', 'เมื่อไหร่', 'เมื่อไร', 'กี่วัน',
  'นานแล้ว', 'นานมาก', 'รอนาน', 'รออยู่', 'ตามเรื่อง', 'ติดตาม', 'ทวง', 'สถานะ', 'ล่าช้า',
  'ช้า', 'แก้ไข', 'ปัญหา', 'ติดปัญหา', 'ไม่สามารถ', 'ใช้ไม่ได้', 'ไม่ขึ้น', 'ไม่ทำงาน',
  'ไม่ได้เลย', 'error', 'ผิด', 'ขอโทษ',
];

export function classify(text: string | null | undefined): UrgencyLevel {
  const t = (text || '').toLowerCase();
  if (t && RED.some((k) => t.includes(k))) return 'red';
  if (t && YELLOW.some((k) => t.includes(k))) return 'yellow';
  return 'green';
}
